/// Karakterin bitmap verisini döndürür.
/// Eğer karakter tabloda yoksa (non-ascii) varsayılan bir blok döndürür.
pub fn get_font_data(c: char) -> [u8; 16] {
    let mut data = [0u8; 16];
    let char_code = c as usize;

    // Önce ASCII tablosunda ara
    if char_code >= 0x20 && char_code <= 0x7E {
        let index = (char_code - 0x20) * 16;
        data.copy_from_slice(&FONT_DATA[index..index + 16]);
        return data;
    }

    // Unicode tablosunda ara
    let unicode = c as u32;
    for (code, font_data) in UNICODE_FONT_DATA.iter() {
        if *code == unicode {
            data.copy_from_slice(font_data);
            return data;
        }
    }

    // Bulunamadı - bilinmeyen karakter için dolu kutu
    data = [
        0xFF, 0x81, 0x81, 0x81, 0x81, 0x81, 0x81, 0xFF, 0x81, 0x81, 0x81, 0x81, 0x81, 0x81, 0x81,
        0xFF,
    ];
    data
}

