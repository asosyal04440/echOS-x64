//!  └──────────────────────────────────────────┘
//!
//!  Karakter indeksi hesabı:
//!  index = (char_code - 0x20) * 16
//!
//!  Örnek: 'A' = 0x41 = 65
//!  index = (65 - 32) * 16 = 528
